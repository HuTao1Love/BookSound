/** Writes TypeScript declarations of the API types to the file named by the first argument. */
fun main(args: Array<String>) {
    val out = File(args.single())
    out.parentFile.mkdirs()
    out.writeText(generateTs())
}

@OptIn(ExperimentalSerializationApi::class)
fun generateTs(): String {
    val declared = LinkedHashMap<String, String>()

    fun nameOf(d: SerialDescriptor) = d.serialName.removeSuffix("?").substringAfterLast('.')

    fun typeOf(d: SerialDescriptor): String {
        val base = when (d.kind) {
            PrimitiveKind.STRING, PrimitiveKind.CHAR -> "string"
            PrimitiveKind.BOOLEAN -> "boolean"
            PrimitiveKind.BYTE, PrimitiveKind.SHORT, PrimitiveKind.INT, PrimitiveKind.LONG,
            PrimitiveKind.FLOAT, PrimitiveKind.DOUBLE -> "number"
            StructureKind.LIST -> "${wrap(typeOf(d.getElementDescriptor(0)))}[]"
            StructureKind.MAP -> "Record<string, ${typeOf(d.getElementDescriptor(1))}>"
            SerialKind.ENUM -> nameOf(d).also { name ->
                if (name !in declared) declared[name] = "export type $name = ${(0 until d.elementsCount).joinToString(" | ") { "\"${d.getElementName(it)}\"" }};"
            }
            StructureKind.CLASS, StructureKind.OBJECT -> nameOf(d).also { name ->
                if (name !in declared) {
                    declared[name] = "" // reserve the slot first: classes may refer to each other
                    val fields = (0 until d.elementsCount).joinToString("\n") { i ->
                        val element = d.getElementDescriptor(i)
                        // Nulls are left out of the JSON, so a nullable field may be missing.
                        val optional = element.isNullable || d.isElementOptional(i)
                        val type = typeOf(element) + if (element.isNullable) " | null" else ""
                        "  ${d.getElementName(i)}${if (optional) "?" else ""}: $type;"
                    }
                    declared[name] = "export interface $name {\n$fields\n}"
                }
            }
            else -> error("Unsupported kind ${d.kind} of ${d.serialName}")
        }
        return base
    }

    roots.forEach { typeOf(it.descriptor) }
    return buildString {
        appendLine("// Generated by ./gradlew :api:generateTs from api/src/main/kotlin. Do not edit.")
        appendLine()
        appendLine("export const API_VERSION = $API_VERSION;")
        appendLine()
        declared.values.forEach { appendLine(it); appendLine() }
    }.trimEnd() + "\n"
}

private fun wrap(type: String) = if (type.contains(' ')) "($type)" else type
